/** 从一段文本里识别学校（返回第一个命中的标签对象） */
function findSchool(text) {
  const s = String(text == null ? '' : text);
  if (!s.trim()) return null;
  for (const sch of SCHOOLS) {
    for (const k of sch.keys) {
      if (s.indexOf(k) >= 0) return { name: sch.name, tags: sch.tags.slice(), note: sch.note || '' };
    }
  }
  return null;
}

/** 从简历正文里找出「最可能属于教育背景」的那一行，再识别学校 */
function detectFromResume(resumeText) {
  const lines = String(resumeText || '').replace(/\r\n?/g, '\n').split('\n');
  const eduStart = lines.findIndex(function (l) { return /教育(背景|经历)|Education/i.test(l); });
  const scope = eduStart >= 0 ? lines.slice(eduStart, eduStart + 12) : lines;
  for (const line of scope) {
    const hit = findSchool(line);
    if (hit) return hit;
  }
  return null;
}

/** 标签 → 用于提示词的一段说明（让 AI 把可核验 Title 写进教育背景） */
function titleBlock(info) {
  if (!info) return '';
  const t = info.tags || [];
  return (info.name || '') + '：' + t.join('、') + (info.note ? '（' + info.note + '）' : '')
    + '\n写法要求：把机构 Title 写进教育条目的 left 字段（如「' + (info.name || '学校') + '｜' + (t[0] || '标签') + '｜学位」），'
    + '只写上面列出的标签，不要自行添加「985 / C9 / 双一流 A 类」等未列出的说法。';
}

